"""Dataset generation and explicit provenance.

'Synthetic' means generated from stated rules, including deliberately nonlinear
label functions. 'Real' means observations in bundled sklearn datasets; those
are curated, finite, and not assumed to represent a deployment environment.
"""
from dataclasses import dataclass
import numpy as np
from sklearn.datasets import load_breast_cancer, load_wine, load_digits, load_diabetes
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler

SYNTHETIC = ("bilinear", "quartic", "sextic", "switched", "additive", "parity6", "noise_only")
REAL = ("breast_cancer", "wine", "digits", "diabetes")

@dataclass
class Dataset:
    name: str
    provenance: str
    task: str
    X_train: np.ndarray
    y_train: np.ndarray
    X_val: np.ndarray
    y_val: np.ndarray
    X_test: np.ndarray
    y_test: np.ndarray
    X_ood: np.ndarray | None = None
    y_ood: np.ndarray | None = None
    source: str = ""


def _make_synthetic(name, n, rng, rotation, support=1.0):
    d = 12
    if name == "noise_only":
        x = rng.uniform(-support,support,(n,d)).astype(np.float32)
        y = rng.standard_normal(n).astype(np.float32)
    elif name == "parity6":
        x = rng.choice([-1., 1.], size=(n,d)).astype(np.float32)
        x += rng.uniform(-0.05,0.05,size=x.shape).astype(np.float32)
        y = np.prod(np.sign(x[:,:6]), axis=1)
    else:
        x = rng.uniform(-support,support,(n,d)).astype(np.float32)
        z = x @ rotation
        if name == "bilinear": y = z[:,0]*z[:,1]
        elif name == "quartic": y = np.prod(z[:,:4], axis=1)
        elif name == "sextic": y = np.prod(z[:,:6], axis=1)
        elif name == "switched": y = np.where(x[:,0]>=0, z[:,0]*z[:,1], z[:,2]*z[:,3])
        elif name == "additive": y = z[:,:4].sum(axis=1)
        else: raise ValueError(name)
    return x.astype(np.float32), np.asarray(y,dtype=np.float32)


def load_dataset(name, seed=0, train_n=1024, val_n=256, test_n=512):
    if name in SYNTHETIC:
        rng = np.random.default_rng(seed + 911)
        rotation, _ = np.linalg.qr(rng.normal(size=(12,12)))
        xtr,ytr = _make_synthetic(name,train_n,rng,rotation)
        xval,yval = _make_synthetic(name,val_n,rng,rotation)
        xte,yte = _make_synthetic(name,test_n,rng,rotation)
        xood,yood = _make_synthetic(name,test_n,rng,rotation,support=1.5)
        if name in ("parity6", "noise_only"):
            xood,yood = None,None
        mu, std = float(ytr.mean()), max(float(ytr.std()),1e-7)
        return Dataset(name,"synthetic","regression",xtr,(ytr-mu)/std,xval,(yval-mu)/std,
                       xte,(yte-mu)/std,xood,((yood-mu)/std if yood is not None else None),
                       source="Generated by _make_synthetic; seed-dependent random orthogonal mixing")
    loaders = {"breast_cancer":load_breast_cancer,"wine":load_wine,"digits":load_digits,"diabetes":load_diabetes}
    if name not in loaders: raise ValueError(name)
    bundle = loaders[name]()
    x = np.asarray(bundle.data,dtype=np.float32)
    y = np.asarray(bundle.target)
    task = "regression" if name == "diabetes" else "classification"
    strat = y if task == "classification" else None
    xa,xt,ya,yt = train_test_split(x,y,test_size=.20,random_state=seed,stratify=strat)
    strat_a = ya if task == "classification" else None
    xtr,xval,ytr,yval = train_test_split(xa,ya,test_size=.20,random_state=seed+20,stratify=strat_a)
    scaler=StandardScaler().fit(xtr)
    # Same input transform for every model; robust against data-dependent outliers.
    xtr=np.clip(scaler.transform(xtr),-4,4).astype(np.float32)/2
    xval=np.clip(scaler.transform(xval),-4,4).astype(np.float32)/2
    xt=np.clip(scaler.transform(xt),-4,4).astype(np.float32)/2
    if task=="regression":
        m,s=float(ytr.mean()),max(float(ytr.std()),1e-7)
        ytr,yval,yt=(ytr-m)/s,(yval-m)/s,(yt-m)/s
        ytr,yval,yt=ytr.astype(np.float32),yval.astype(np.float32),yt.astype(np.float32)
    else:
        ytr,yval,yt=ytr.astype(np.int64),yval.astype(np.int64),yt.astype(np.int64)
    return Dataset(name,"real_observational","regression" if name=="diabetes" else task,
                   xtr,ytr,xval,yval,xt,yt,
                   source=f"scikit-learn bundled {name} dataset (curated observational data)")
